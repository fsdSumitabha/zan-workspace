"use client"

/**
 * Renders compiled email HTML inside a sandboxed iframe.
 *
 * ## Why an iframe and not a div
 *
 * Email HTML carries its own `<style>` rules and table layout. Dropping it
 * into the app's DOM would let those rules reach the CRM's own chrome, and
 * the CRM's Tailwind would in turn change how the email looks, so the
 * preview would be wrong in both directions.
 *
 * ## Why the sandbox is empty
 *
 * `sandbox=""` is the strictest setting the browser offers: no scripts, no
 * forms, no navigation, no plugins, and a null origin with no access to our
 * cookies or storage. The HTML is machine-generated by MJML from content an
 * author typed, and validate.ts and sanitize.ts already strip anything
 * executable. This is the third layer.
 *
 * ## Why srcDoc and not document.write
 *
 * An empty sandbox also means the parent cannot reach `contentDocument`:
 * the frame is cross-origin to us by design. Writing into it from here
 * silently does nothing and leaves a blank white box. `srcDoc` hands the
 * markup to the browser instead, which is the only way to fill a frame this
 * strict.
 *
 * React swapping the whole frame on a content change is not a problem here.
 * The preview opens on demand and is not re-rendered per keystroke.
 */
export default function PreviewFrame({
    html,
    device,
    className,
}: {
    html: string
    device: "desktop" | "mobile"
    className?: string
}) {
    return (
        <div
            className={`flex justify-center overflow-auto bg-slate-200 p-4 dark:bg-neutral-900 ${className ?? ""}`}
        >
            <iframe
                title="Email preview"
                sandbox=""
                srcDoc={html}
                className="h-full border-0 bg-white shadow-sm transition-[width] duration-200"
                style={{
                    width: device === "mobile" ? 375 : "100%",
                    maxWidth: device === "mobile" ? 375 : 800,
                    minHeight: 480,
                }}
            />
        </div>
    )
}

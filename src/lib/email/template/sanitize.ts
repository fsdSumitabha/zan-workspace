/**
 * Strips anything executable from compiled email HTML.
 *
 * ## Why this runs even though validate.ts already refused scripts
 *
 * validate.ts checks the MJML source. This checks the output. They are not
 * the same thing: MJML has tags such as `mj-raw` and `mj-style` that pass
 * content through, and a future MJML version could emit something new. One
 * check at the door and one at the exit is the point.
 *
 * ## Why it matters when mail clients strip scripts anyway
 *
 * Because we render this HTML ourselves, in the preview and in the test
 * send. The preview iframe is sandboxed without allow-scripts, so a script
 * could not run there either, but defence that rests on one flag in one
 * component is defence that breaks the day somebody edits that component.
 *
 * This is deliberately a small, readable set of rules rather than a full
 * HTML parser. The input is machine-generated by MJML, not arbitrary web
 * HTML, and validate.ts has already refused the obvious attacks.
 */

const RULES: Array<{ re: RegExp; replace: string }> = [
    // Script blocks, with or without a closing tag.
    { re: /<script[\s\S]*?<\/script\s*>/gi, replace: "" },
    { re: /<script\b[^>]*>/gi, replace: "" },

    // Embedded documents and plugins.
    { re: /<iframe[\s\S]*?<\/iframe\s*>/gi, replace: "" },
    { re: /<iframe\b[^>]*>/gi, replace: "" },
    { re: /<object[\s\S]*?<\/object\s*>/gi, replace: "" },
    { re: /<embed\b[^>]*>/gi, replace: "" },
    { re: /<form[\s\S]*?<\/form\s*>/gi, replace: "" },
    { re: /<form\b[^>]*>/gi, replace: "" },

    // Inline event handlers: onclick, onerror, onload and the rest.
    { re: /\son[a-z]+\s*=\s*"[^"]*"/gi, replace: "" },
    { re: /\son[a-z]+\s*=\s*'[^']*'/gi, replace: "" },
    { re: /\son[a-z]+\s*=\s*[^\s>]+/gi, replace: "" },

    // Script URLs in href, src and background.
    { re: /(href|src|background)\s*=\s*"\s*javascript:[^"]*"/gi, replace: '$1="#"' },
    { re: /(href|src|background)\s*=\s*'\s*javascript:[^']*'/gi, replace: "$1='#'" },

    // data: URLs, except images. A data:text/html href is a script vector.
    {
        re: /(href|src)\s*=\s*"\s*data:(?!image\/)[^"]*"/gi,
        replace: '$1="#"',
    },
    {
        re: /(href|src)\s*=\s*'\s*data:(?!image\/)[^']*'/gi,
        replace: "$1='#'",
    },

    // CSS expression(), an old IE script vector that still trips scanners.
    { re: /expression\s*\(/gi, replace: "expr-removed(" },
]

export function sanitizeEmailHtml(html: string): string {
    let out = html
    for (const { re, replace } of RULES) {
        out = out.replace(re, replace)
    }
    return out
}

/**
 * True when sanitising would change the input.
 *
 * The save route uses this to tell the author that something was removed,
 * rather than silently changing what they wrote.
 */
export function wouldSanitize(html: string): boolean {
    return sanitizeEmailHtml(html) !== html
}
